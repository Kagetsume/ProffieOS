#!/usr/bin/env node
/**
 * Merges SD/layer color names from colors.json (firmware + extended + vivid),
 * then Fett263 Edit Mode color_list_ (voice labels), into one compile-time table.
 *
 * Duplicate names (case-insensitive): first source wins — firmware, then extended,
 * then vivid, then Fett263. RGB conflicts are skipped and logged (catalog aligns
 * with the LayerBlade website).
 *
 * Run from repo root: node tools/generate-parse-color-names.js
 * Output: styles/parse_color_arg_table.generated.h (committed; Arduino needs no Node).
 */

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');
const CATALOG_JSON = path.join(REPO_ROOT, 'website', 'src', 'catalog', 'colors.json');
const COLORS_H = path.join(REPO_ROOT, 'styles', 'colors.h');
const FETT263_SOURCE = path.join(REPO_ROOT, 'props', 'saber_fett263_buttons.h');
const OUT_HEADER = path.join(REPO_ROOT, 'styles', 'parse_color_arg_table.generated.h');

const RGB_TYPEDEF_RE = /typedef\s+Rgb<(\d+),\s*(\d+),\s*(\d+)>\s+(\w+);/g;

function normKey(name) {
  return name.toLowerCase();
}

function parseColorsH(sourceText) {
  const map = new Map();
  let m;
  while ((m = RGB_TYPEDEF_RE.exec(sourceText)) !== null) {
    map.set(m[4], { r: Number(m[1]), g: Number(m[2]), b: Number(m[3]) });
  }
  return map;
}

function c16ChannelTo8(v) {
  return v > 255 ? Math.round(v / 257) : v;
}

function colorNumberToName(colorNumber) {
  const prefix = 'COLOR_';
  if (!colorNumber.startsWith(prefix)) return colorNumber.toLowerCase();
  return colorNumber.slice(prefix.length).toLowerCase();
}

function parseFett263ColorList(sourceText, colorsH) {
  const listStart = sourceText.indexOf('static constexpr ColorListEntry color_list_[]');
  if (listStart < 0) throw new Error('color_list_ not found in saber_fett263_buttons.h');
  const braceStart = sourceText.indexOf('{', listStart);
  let depth = 0;
  let i = braceStart;
  for (; i < sourceText.length; i++) {
    if (sourceText[i] === '{') depth++;
    else if (sourceText[i] === '}') {
      depth--;
      if (depth === 0) break;
    }
  }
  const body = sourceText.slice(braceStart + 1, i);
  const lineRe =
    /\{\s*(?:([A-Za-z]+)::color\(\)|\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\})\s*,\s*(COLOR_\w+)\s*\}/g;
  const entries = [];
  let m;
  while ((m = lineRe.exec(body)) !== null) {
    let r;
    let g;
    let b;
    if (m[1]) {
      const rgb = colorsH.get(m[1]);
      if (!rgb) {
        throw new Error(`Unknown color type ${m[1]} in color_list_ (check styles/colors.h)`);
      }
      ({ r, g, b } = rgb);
    } else {
      r = c16ChannelTo8(Number(m[2]));
      g = c16ChannelTo8(Number(m[3]));
      b = c16ChannelTo8(Number(m[4]));
    }
    entries.push({
      name: colorNumberToName(m[5]),
      r,
      g,
      b,
      source: 'fett263',
    });
  }
  return entries;
}

function addEntry(map, entry, conflicts) {
  const key = normKey(entry.name);
  const existing = map.get(key);
  if (existing) {
    if (existing.r !== entry.r || existing.g !== entry.g || existing.b !== entry.b) {
      conflicts.push({
        name: entry.name,
        kept: existing,
        skipped: entry,
      });
    }
    return;
  }
  map.set(key, entry);
}

function mergeCatalog(catalog) {
  const order = [];
  const groups = [
    ['firmware', catalog.firmware || []],
    ['extended', catalog.extended || []],
    ['vivid', catalog.vivid || []],
  ];
  for (const [source, list] of groups) {
    for (const c of list) {
      order.push({
        name: c.name,
        r: c.r,
        g: c.g,
        b: c.b,
        source,
      });
    }
  }
  return order;
}

function emitHeader(entries) {
  const lines = entries.map(
    (e) => `    {"${e.name}", ${String(e.r).padStart(3)}, ${String(e.g).padStart(3)}, ${String(e.b).padStart(3)}}`
  );
  return `// AUTO-GENERATED by tools/generate-parse-color-names.js — do not edit.
#ifndef STYLES_PARSE_COLOR_ARG_TABLE_GENERATED_H
#define STYLES_PARSE_COLOR_ARG_TABLE_GENERATED_H

// Merged SD/layer color names (${entries.length} entries). Regenerate after catalog or Fett263 list changes.

struct ParseColorNameEntry { const char* n; uint8_t r, g, b; };

static const ParseColorNameEntry parse_color_name_table[] = {
${lines.join(',\n')}
};

#endif
`;
}

function main() {
  const catalog = JSON.parse(fs.readFileSync(CATALOG_JSON, 'utf8'));
  const colorsH = parseColorsH(fs.readFileSync(COLORS_H, 'utf8'));
  const fett263 = parseFett263ColorList(fs.readFileSync(FETT263_SOURCE, 'utf8'), colorsH);

  const map = new Map();
  const conflicts = [];
  const entries = [];

  function ingest(entry) {
    const key = normKey(entry.name);
    if (map.has(key)) {
      addEntry(map, entry, conflicts);
      return;
    }
    map.set(key, entry);
    entries.push(entry);
  }

  for (const entry of mergeCatalog(catalog)) {
    ingest(entry);
  }
  for (const entry of fett263) {
    ingest(entry);
  }

  fs.writeFileSync(OUT_HEADER, emitHeader(entries), 'utf8');

  console.log(`Wrote ${path.relative(REPO_ROOT, OUT_HEADER)} (${entries.length} names)`);
  if (conflicts.length) {
    console.log(`Skipped ${conflicts.length} duplicate name(s) with different RGB (first source wins):`);
    for (const c of conflicts) {
      console.log(
        `  ${c.name}: kept ${c.kept.r},${c.kept.g},${c.kept.b} (${c.kept.source}) — skipped ${c.skipped.r},${c.skipped.g},${c.skipped.b} (${c.skipped.source})`
      );
    }
  }
}

main();
